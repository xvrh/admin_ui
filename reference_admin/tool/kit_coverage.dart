// Which of admin_ui's public symbols this app uses, per barrel.
//
//   fvm dart run tool/kit_coverage.dart [--check]
//
// Reads ../packages/admin_ui/api.txt, looks for each non-deprecated
// exported symbol as a whole word in lib/ (comments left out), and writes
// KIT_COVERAGE.md. coverage_exclusions.yaml says why each unused symbol is
// unused. A regex, not the analyzer: cheap, and a false positive is rare
// and harmless. test/unit/guards_test.dart calls [coverage] and
// [renderCoverage].

import 'dart:io';

import 'package:yaml/yaml.dart';

class KitSymbol {
  final String barrel;
  final String name;
  const KitSymbol(this.barrel, this.name);
}

class KitCoverage {
  final List<KitSymbol> symbols;

  /// Symbol name → the first lib/ file using it, package-relative.
  final Map<String, String> usedIn;

  /// Symbol name → the exclusion group explaining why it is left out.
  final Map<String, String> exclusions;

  /// Exclusion group → its reason.
  final Map<String, String> reasons;

  const KitCoverage(this.symbols, this.usedIn, this.exclusions, this.reasons);

  List<KitSymbol> get unused => [
    for (final s in symbols)
      if (!usedIn.containsKey(s.name)) s,
  ];

  /// Unused symbols no exclusion explains.
  List<KitSymbol> get unexplained => [
    for (final s in unused)
      if (!exclusions.containsKey(s.name)) s,
  ];

  /// Exclusions for symbols the app now uses.
  List<String> get staleExclusions => [
    for (final name in exclusions.keys)
      if (usedIn.containsKey(name)) name,
  ];
}

/// The public symbols api.txt lists, deprecated aliases and re-export lines
/// left out.
List<KitSymbol> kitSymbols(String apiTxt) => [
  for (final line in apiTxt.split('\n'))
    if (line.isNotEmpty &&
        !line.startsWith('#') &&
        !line.contains(' re-exports ') &&
        !line.endsWith('(deprecated)'))
      KitSymbol(line.split(' ')[0], line.split(' ')[1]),
];

/// [source] without its comments, so a doc comment naming a kit symbol
/// does not count as using it.
String withoutComments(String source) => [
  for (final line in source.split('\n'))
    line.replaceFirst(RegExp(r'//.*$'), ''),
].join('\n');

/// coverage_exclusions.yaml read as (group by symbol, reason by group).
(Map<String, String>, Map<String, String>) readExclusions(String yaml) {
  final doc = loadYaml(yaml);
  final groups = <String, String>{};
  final reasons = <String, String>{};
  if (doc is! YamlMap) return (groups, reasons);
  for (final MapEntry(:key, :value) in doc.entries) {
    if (value is! YamlMap) continue;
    reasons['$key'] = '${value['reason']}';
    for (final symbol in (value['symbols'] as YamlList? ?? YamlList())) {
      groups['$symbol'] = '$key';
    }
  }
  return (groups, reasons);
}

/// The coverage of the package at [root].
KitCoverage coverage(Directory root) {
  final api = File('${root.path}/../packages/admin_ui/api.txt');
  final symbols = kitSymbols(api.readAsStringSync());
  final files =
      Directory('${root.path}/lib')
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final sources = {
    for (final f in files)
      f.path.substring(root.path.length + 1): withoutComments(
        f.readAsStringSync(),
      ),
  };
  final usedIn = <String, String>{};
  for (final symbol in symbols) {
    final word = RegExp('\\b${RegExp.escape(symbol.name)}\\b');
    for (final MapEntry(key: path, value: source) in sources.entries) {
      if (word.hasMatch(source)) {
        usedIn[symbol.name] = path;
        break;
      }
    }
  }
  final file = File('${root.path}/coverage_exclusions.yaml');
  final (exclusions, reasons) = file.existsSync()
      ? readExclusions(file.readAsStringSync())
      : (const <String, String>{}, const <String, String>{});
  return KitCoverage(symbols, usedIn, exclusions, reasons);
}

String renderCoverage(KitCoverage c) {
  final barrels = <String>[];
  for (final s in c.symbols) {
    if (!barrels.contains(s.barrel)) barrels.add(s.barrel);
  }
  final used = c.symbols.length - c.unused.length;
  final out = StringBuffer()
    ..writeln('# Kit coverage')
    ..writeln()
    ..writeln(
      'GENERATED by `fvm dart run tool/kit_coverage.dart` from '
      '`packages/admin_ui/api.txt`: do not edit by hand.',
    )
    ..writeln()
    ..writeln(
      '$used of ${c.symbols.length} public symbols are used in `lib/`. '
      'Each unused one is explained in `coverage_exclusions.yaml`:',
    )
    ..writeln();
  for (final MapEntry(:key, :value) in c.reasons.entries) {
    out.writeln('- `$key`: $value');
  }
  for (final barrel in barrels) {
    final inBarrel = [
      for (final s in c.symbols)
        if (s.barrel == barrel) s,
    ];
    final usedHere = [
      for (final s in inBarrel)
        if (c.usedIn.containsKey(s.name)) s,
    ];
    out
      ..writeln()
      ..writeln('## $barrel: ${usedHere.length} of ${inBarrel.length}')
      ..writeln();
    if (usedHere.isNotEmpty) {
      out
        ..writeln('| Used | Example |')
        ..writeln('|---|---|');
      for (final s in usedHere) {
        out.writeln('| `${s.name}` | `${c.usedIn[s.name]}` |');
      }
      out.writeln();
    }
    final unusedHere = [
      for (final s in inBarrel)
        if (!c.usedIn.containsKey(s.name)) s,
    ];
    if (unusedHere.isNotEmpty) {
      out
        ..writeln('| Not used | Why |')
        ..writeln('|---|---|');
      for (final s in unusedHere) {
        final group = c.exclusions[s.name];
        out.writeln('| `${s.name}` | ${group == null ? '—' : '`$group`'} |');
      }
    }
  }
  return out.toString();
}

void main(List<String> args) {
  final root = Directory.current;
  final rendered = renderCoverage(coverage(root));
  final file = File('${root.path}/KIT_COVERAGE.md');
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != rendered) {
      stderr.writeln('KIT_COVERAGE.md is stale: run tool/kit_coverage.dart');
      exitCode = 1;
    }
    return;
  }
  file.writeAsStringSync(rendered);
  final c = coverage(root);
  stdout.writeln(
    '${c.symbols.length - c.unused.length}/${c.symbols.length} used, '
    '${c.unexplained.length} unexplained',
  );
}
