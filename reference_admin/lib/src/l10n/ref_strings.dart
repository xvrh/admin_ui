class _RefStringsDelegate extends LocalizationsDelegate<RefStrings> {
  const _RefStringsDelegate();

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<RefStrings> load(Locale locale) =>
      SynchronousFuture(RefStrings.lookup(locale));

  @override
  bool shouldReload(_RefStringsDelegate old) => false;
}

extension RefStringsContext on BuildContext {
  /// The app's strings in this context's language.
  RefStrings get strings => RefStrings.of(this);
}
