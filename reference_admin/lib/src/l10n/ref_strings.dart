/// The app's own strings, in English, French and Arabic, one section per
/// area so each area's owner edits one file.
///
/// Hand-written in the kit's own style rather than generated by gen-l10n,
/// whose delegate list pulls in `flutter_localizations`.
// FRICTION(F-010): the kit documents no pattern for an app's own strings.
abstract class RefStrings {
  const RefStrings(this.localeName);

  final String localeName;

  static const LocalizationsDelegate<RefStrings> delegate =
      _RefStringsDelegate();

  /// The strings for [context]'s locale; English without the delegate.
  static RefStrings of(BuildContext context) =>
      Localizations.of<RefStrings>(context, RefStrings) ?? const RefStringsEn();

  static RefStrings lookup(Locale locale) => switch (locale.languageCode) {
    'fr' => const RefStringsFr(),
    'ar' => const RefStringsAr(),
    _ => const RefStringsEn(),
  };

  ShellStrings get shell;
  AccessStrings get access;
  OrdersStrings get orders;
  CatalogueStrings get catalogue;
  MediaTeamStrings get mediaTeam;
  SettingsStrings get settings;
}

class RefStringsEn extends RefStrings {
  const RefStringsEn() : super('en');
  @override
  ShellStrings get shell => const ShellStringsEn();
  @override
  AccessStrings get access => const AccessStringsEn();
  @override
  OrdersStrings get orders => const OrdersStringsEn();
  @override
  CatalogueStrings get catalogue => const CatalogueStringsEn();
  @override
  MediaTeamStrings get mediaTeam => const MediaTeamStringsEn();
  @override
  SettingsStrings get settings => const SettingsStringsEn();
}

