// Writes each kit language's intl date data, from package:intl's own, into
// lib/src/l10n/languages/<language>/date_data.dart, and a regional variant's
// into the date_data_<language>_<country>.dart beside it: en_GB's into
// en/date_data_en_gb.dart. A new variant starts as an empty file there.
//
//   fvm dart run tool/gen_date_data.dart
//
// intl keeps every locale's date symbols and patterns in one map, so an app
// that loads them from there ships all of them; a kit language carries its
// own copy and loads only that. test/l10n_date_data_test.dart fails when a
// copy no longer matches intl's.

import 'dart:io';

import 'package:dart_style/dart_style.dart';
import 'package:intl/date_symbol_data_local.dart';
import 'package:intl/date_time_patterns.dart';

final _formatter = DartFormatter(
  languageVersion: DartFormatter.latestLanguageVersion,
);

void main() {
  final root = Directory('lib/src/l10n/languages');
  final languages = [
    for (final dir in root.listSync().whereType<Directory>())
      dir.uri.pathSegments.where((s) => s.isNotEmpty).last,
  ]..sort();
  final symbols = dateTimeSymbolMap();
  final patterns = dateTimePatternMap();
  final variant = RegExp(r'^date_data_([a-z]+)_([a-z]+)\.dart$');
  for (final language in languages) {
    final dir = Directory('${root.path}/$language');
    final outs = {
      language: File('${dir.path}/date_data.dart'),
      for (final file in dir.listSync().whereType<File>())
        if (variant.firstMatch(file.uri.pathSegments.last) case final m?)
          '${m[1]}_${m[2]!.toUpperCase()}': file,
    };
    for (final MapEntry(key: locale, value: out) in outs.entries) {
      final data = symbols[locale];
      if (data == null) {
        stderr.writeln('intl has no date data for "$locale".');
        exitCode = 1;
        continue;
      }
      out.writeAsStringSync(
        _formatter.format(
          _source(locale, data.serializeToMap(), patterns[locale]!),
        ),
      );
      stdout.writeln('wrote ${out.path}');
    }
  }
}

String _source(
  String language,
  Map<String, dynamic> symbols,
  Map<String, String> patterns,
) {
  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_date_data.dart from package:intl — do not',
    )
    ..writeln(
      '// edit by hand. Run `fvm dart run tool/gen_date_data.dart` to refresh.',
    )
    ..writeln()
    ..writeln("import 'package:intl/date_symbols.dart';")
    ..writeln()
    ..writeln("/// intl's date symbols for '$language'.")
    ..writeln('DateSymbols dateSymbols() => DateSymbols(');
  for (final MapEntry(:key, :value) in symbols.entries) {
    if (value == null) continue;
    b.writeln('  $key: ${_literal(value)},');
  }
  b
    ..writeln(');')
    ..writeln()
    ..writeln("/// intl's date patterns for '$language'.")
    ..writeln('const datePatterns = <String, String>{');
  for (final MapEntry(:key, :value) in patterns.entries) {
    b.writeln('  ${_string(key)}: ${_string(value)},');
  }
  b.writeln('};');
  return b.toString();
}

String _literal(Object value) => switch (value) {
  String() => _string(value),
  int() => '$value',
  List<Object?>() => 'const [${value.map((v) => _literal(v!)).join(', ')}]',
  Map<Object?, Object?>() =>
    'const <String, String>{${value.entries.map((e) => '${_string('${e.key}')}: ${_string('${e.value}')}').join(', ')}}',
  _ => throw ArgumentError('Unexpected date data value: $value'),
};

String _string(String s) {
  final escaped = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
