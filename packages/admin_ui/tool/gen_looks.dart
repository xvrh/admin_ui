// Generates looks.txt, every shipped theme's resolved tokens, so a change of
// look shows in review as api.txt shows a change of API.
//
//   dart run tool/gen_looks.dart           # write test/looks/describe.gen.dart and looks.txt
//   dart run tool/gen_looks.dart --check   # fail if either is out of date
//
// The tokens are Flutter objects, so the dump runs under `flutter test`
// (test/looks_test.dart). What it walks is generated here: every token class
// reachable from AdminTokens, each public instance field described in turn,
// a field whose type is another token class by recursion. A field added to a
// token class is in the dump at the next run, and test/looks_test.dart fails
// until the generated walk and looks.txt are rewritten.

import 'dart:io';

import 'package:analyzer/dart/analysis/features.dart';
import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:dart_style/dart_style.dart';

const describerPath = 'test/looks/describe.gen.dart';

/// The token class every theme resolves to, where the walk starts.
const _root = 'AdminTokens';

/// The source of [describerPath] for the package at [root].
String generateDescribers(String root) {
  final classes = <String, List<(String name, String? type)>>{};
  final files = <String, String>{};
  final src = Directory('$root/lib/src');
  final sources = src.listSync(recursive: true).whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in sources) {
    if (!file.path.endsWith('.dart')) continue;
    final unit = parseString(
      content: file.readAsStringSync(),
      featureSet: FeatureSet.latestLanguageVersion(),
      throwIfDiagnostics: false,
    ).unit;
    for (final declaration in unit.declarations.whereType<ClassDeclaration>()) {
      final fields = <(String, String?)>[];
      for (final member
          in declaration.body.members.whereType<FieldDeclaration>()) {
        if (member.isStatic) continue;
        final type = member.fields.type?.toSource();
        for (final variable in member.fields.variables) {
          final name = variable.name.lexeme;
          if (name.startsWith('_')) continue;
          fields.add((name, type));
        }
      }
      final name = declaration.namePart.typeName.lexeme;
      classes[name] = fields;
      files[name] = file.path;
    }
  }

  final reached = <String>[];
  void reach(String name) {
    if (reached.contains(name)) return;
    reached.add(name);
    for (final (field, type) in classes[name]!) {
      if (type == null) {
        throw StateError('${files[name]}: $name.$field has no declared type');
      }
      final bare = type.replaceAll('?', '');
      if (_isTokenClass(classes, bare)) reach(bare);
    }
  }

  reach(_root);

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_looks.dart. Do not edit.')
    ..writeln()
    ..writeln("import 'package:admin_ui/admin_ui.dart';")
    ..writeln("import 'format.dart';")
    ..writeln();
  for (final name in reached) {
    out
      ..writeln(
        'void describe$name($name v, String path, Map<String, String> out) {',
      )
      ..writeln('  final p = path.isEmpty ? \'\' : \'\$path.\';');
    for (final (field, type!) in classes[name]!) {
      final bare = type.replaceAll('?', '');
      final nullable = type.endsWith('?');
      if (_isTokenClass(classes, bare)) {
        if (nullable) {
          out
            ..writeln('  if (v.$field case final f?) {')
            ..writeln("    describe$bare(f, '\${p}$field', out);")
            ..writeln('  } else {')
            ..writeln("    out['\${p}$field'] = 'null';")
            ..writeln('  }');
        } else {
          out.writeln("  describe$bare(v.$field, '\${p}$field', out);");
        }
      } else {
        out.writeln("  describeValue(v.$field, '\${p}$field', out);");
      }
    }
    out
      ..writeln('}')
      ..writeln();
  }
  return DartFormatter(languageVersion: DartFormatter.latestLanguageVersion)
      .format(out.toString());
}

bool _isTokenClass(Map<String, List<(String, String?)>> classes, String name) =>
    classes[name]?.isNotEmpty ?? false;

/// The `flutter` of the SDK running this script: under fvm, the pinned one.
String get _flutter {
  final dart = File(Platform.resolvedExecutable);
  // <sdk>/bin/cache/dart-sdk/bin/dart
  final sdk = dart.parent.parent.parent.parent.parent;
  final flutter = File('${sdk.path}/bin/flutter');
  return flutter.existsSync() ? flutter.path : 'flutter';
}

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final root = Directory.current.path;
  final describers = generateDescribers(root);
  final file = File('$root/$describerPath');
  if (check) {
    if (!file.existsSync() || file.readAsStringSync() != describers) {
      stderr.writeln(
        '$describerPath is stale: run dart run tool/gen_looks.dart',
      );
      exitCode = 1;
      return;
    }
  } else {
    file
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(describers);
  }
  final result = await Process.start(
    _flutter,
    ['test', 'test/looks_test.dart'],
    environment: {if (!check) 'UPDATE_LOOKS': '1'},
    mode: ProcessStartMode.inheritStdio,
  );
  exitCode = await result.exitCode;
}
