/// Reads the kit's strings from a [BuildContext].
extension AdminLocalizationsContext on BuildContext {
  /// [AdminLocalizations.of] this context: English without a delegate.
  AdminLocalizations get adminL10n => AdminLocalizations.of(this);
}

class _AdminLocalizationsDelegate
    extends LocalizationsDelegate<AdminLocalizations> {
  const _AdminLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<AdminLocalizations> load(Locale locale) =>
      SynchronousFuture(AdminLocalizations.lookup(locale));

  @override
  bool shouldReload(_AdminLocalizationsDelegate old) => false;
}
