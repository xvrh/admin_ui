/// The kit's own strings, in one language: [AdminLocalizationsEn] here,
/// the kit's other languages in their own libraries.
///
/// An app loads them with the [AdminLanguages] it ships, and the kit's
/// widgets read them with `context.adminL10n`:
///
/// ```dart
/// const languages = AdminLanguages([adminEn, adminFr]);
///
/// MaterialApp(
///   localizationsDelegates: languages.delegates,
///   supportedLocales: languages.locales,
/// )
/// ```
///
/// Without a delegate nothing fails: [of] answers English. A language the
/// app does not list also gets English strings, while numbers and dates
/// still follow the app's locale ([AdminFormats]). In a right-to-left
/// language without strings, such as Hebrew, that English sits in
/// right-to-left text, where a trailing ellipsis or number lands on the
/// wrong side; an app shipping one should supply its strings (below).
///
/// A widget resolves each of its strings in this order:
///
/// 1. The widget's own label parameter, when the caller passed one.
/// 2. The shared vocabulary on this class: words two or more areas of the
///    kit use, such as [apply], [cancel] or [selectedCount]. It holds the
///    buttons and labels Material also has ([save], [pageRowsInfo], the
///    `keyboardKey*` names [shortcutLabel] writes), worded as Material's
///    translations word them, so that an override reaches them too.
/// 3. The area's section: [inputs], [display], [collection], [fields],
///    [shell] or [assets].
///
/// To change strings, subclass the language's class (or a section's,
/// returned from the section getter) and give it to that language with
/// [AdminLanguage.copyWith]:
///
/// ```dart
/// class MyInputs extends InputsMessagesEn {
///   const MyInputs();
///   // @override members of InputsMessages here.
/// }
///
/// class MyAdminL10n extends AdminLocalizationsEn {
///   const MyAdminL10n();
///   @override
///   String get apply => 'Go';
///   @override
///   InputsMessages get inputs => const MyInputs();
/// }
///
/// final languages = AdminLanguages([
///   adminEn.copyWith(strings: const MyAdminL10n()),
/// ]);
/// ```
///
/// A delegate of the app's own for [AdminLocalizations], listed before the
/// kit's, also wins: [of] reads one before the [AdminLanguage].
///
/// Hand-written rather than generated by gen-l10n, whose output imports
/// `package:flutter_localizations`'s copy of Material and whose `of` asserts
/// when the delegate is missing.
abstract class AdminLocalizations extends AdminMessages {
  const AdminLocalizations(super.localeName);

  /// Loads the kit's strings in English, French and Arabic, for every locale,
  /// English for any other language.
  @Deprecated(
    'Use AdminLanguages([adminEn, adminFr, adminAr]).delegates, which loads '
    'the languages an app lists and no others.',
  )
  static const LocalizationsDelegate<AdminLocalizations> delegate =
      LegacyAdminLocalizationsDelegate();

  /// English, French and Arabic.
  @Deprecated(
    'Use AdminLanguages([adminEn, adminFr, adminAr]).locales, the locales of '
    'the languages an app lists.',
  )
  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('fr'),
    Locale('ar'),
  ];

  /// [delegate] and material_ui's Material, Cupertino and widgets delegates,
  /// which bring Material's 82 languages.
  @Deprecated(
    'Use AdminLanguages([adminEn, adminFr, adminAr]).delegates, which brings '
    "Material's strings for the languages an app lists, and no others.",
  )
  static const localizationsDelegates = <LocalizationsDelegate<Object?>>[
    delegate,
    ...GlobalMaterialLocalizations.delegates,
  ];

  /// The strings for [context]'s locale: a delegate's for
  /// [AdminLocalizations], else the [AdminLanguage]'s that
  /// [AdminLanguages.delegates] loaded, else English. Never asserts.
  static AdminLocalizations of(BuildContext context) =>
      Localizations.of<AdminLocalizations>(context, AdminLocalizations) ??
      AdminLanguage.of(context)?.strings ??
      const AdminLocalizationsEn();

  /// The kit's own strings for [locale]'s language among English, French
  /// and Arabic, English for any other.
  @Deprecated(
    "Read AdminLocalizations.of(context), or a language's strings: "
    'adminFr.strings.',
  )
  static AdminLocalizations lookup(Locale locale) => legacyLookup(locale);

  /// The inputs, menus, pickers and overlays in common/ui.
  InputsMessages get inputs;

  /// The layout, data display, feedback, history, menu-editor and
  /// block-picker widgets.
  DisplayMessages get display;

  /// The collection kit: the table, toolbar, filters, pager and views.
  CollectionMessages get collection;

  /// The field bodies, the language lanes and their translation status
  /// words, and the comments capability.
  FieldsMessages get fields;

  /// The app shell, the auth forms and the generic form save flow.
  ShellMessages get shell;

  /// The asset library, picker, cropper and editor.
  AssetsMessages get assets;

  /// A button that applies pending choices, such as a filter's.
  String get apply;

  /// A button that repeats what failed.
  String get retry;

  /// Takes something out of a list or a field, without deleting it.
  String get remove;

  /// [remove] for one named thing: an accessible name, a tooltip.
  String removeItem(String name);

  /// Puts settings back to their defaults.
  String get reset;

  /// Something is on its way, with a trailing ellipsis.
  String get loading;

  /// Changes are being saved, with a trailing ellipsis.
  String get saving;

  /// A value or a record differs from its saved version.
  String get edited;

  /// A form, or a view, has changes that are not saved yet.
  String get unsavedChanges;

  /// A search found nothing.
  String get noResults;

  /// A filter over a loaded list kept nothing.
  String get noMatches;

  /// Data could not be fetched: a list, a preview, a set of options.
  String get couldNotLoad;

  /// A search request failed, as opposed to finding nothing.
  String get searchFailed;

  /// Fetches the next page of a list.
  String get loadMore;

  /// A search request is in flight, with a trailing ellipsis.
  String get searching;

  /// The headline of an error with no better description.
  String get somethingWentWrong;

  /// A whole sentence for an error with no better description.
  String get somethingWentWrongTryAgain;

  /// The headline of a page or a panel the signed-in user may not open.
  String get notAllowed;

  /// A whole sentence under that headline, saying who can change it.
  String get notAllowedAskAdministrator;

  /// Leaves a page the user may not open, or has no use for.
  String get goBack;

  /// The overflow menu of secondary actions.
  String get moreActions;

  /// Deselects everything.
  String get clearSelection;

  /// Reorders an item one place earlier.
  String get moveUp;

  /// Reorders an item one place later.
  String get moveDown;

  /// The placeholder of a select with nothing chosen.
  String get selectPlaceholder;

  /// The placeholder of a filter box inside a list.
  String get filterPlaceholder;

  /// The placeholder of a search box.
  String get searchPlaceholder;

  /// Appends an item to a list or a repeater.
  String get addItem;

  /// Appends a row to a table or a key-value list.
  String get addRow;

  /// The key column of a key-value list.
  String get keyLabel;

  /// The value column of a key-value list.
  String get valueLabel;

  /// The placeholder of a reference picker with nothing linked.
  String get linkPlaceholder;

  /// Puts one field back to its published value.
  String get restoreLiveVersion;

  /// A referenced asset that no longer exists.
  String get assetNotFound;

  /// The accessible name of an asset's thumbnail.
  String get assetPreview;

  /// An upload that did not complete.
  String get uploadFailed;

  /// The prompt of an upload drop zone, split around the part drawn as a
  /// link: `before`, `link` and `after` read together as "Drag & drop
  /// files, or browse". [multiple] asks for files rather than a file, and
  /// [images] names images rather than files.
  ({String before, String link, String after}) dropPrompt({
    required bool multiple,
    bool images = false,
  });

  /// How many items are selected, "Nothing selected" at zero.
  String selectedCount(int count);

  /// [count] out of [total]: "3 of 12".
  String countOf(int count, int total);

  /// A byte size: [amount] is already formatted in the unit of 1000^[power]
  /// bytes, 0 for bytes up to 4 for terabytes. Used by
  /// [AdminFormats.bytes].
  String byteSize(String amount, int power);

  /// The label of a button that closes a dialog or a prompt and keeps
  /// everything as it was.
  String get cancel;

  /// The label of a button that saves.
  String get save;

  /// The label of a button that deletes.
  String get delete;

  /// The label of a button that copies to the clipboard.
  String get copy;

  /// The label of a button that closes a panel, a sheet or a message.
  String get close;

  /// The label of a button that empties a field.
  String get clear;

  /// The accessible name of a search field.
  String get search;

  /// The label of a button that opens the actions that did not fit.
  String get more;

  /// The label of a control that selects every item.
  String get selectAll;

  /// The accessible name of what closes an overlay: its barrier, or the
  /// close button of a message.
  String get dismiss;

  /// The label of a pager's page size menu.
  String get rowsPerPage;

  /// The rows a page shows, out of all of them: "1–25 of 1,234". The
  /// numbers are already formatted.
  String pageRowsInfo(String first, String last, String total);

  /// The label of the button that goes to the previous page.
  String get previousPage;

  /// The label of the button that goes to the next page.
  String get nextPage;

  /// The label of a calendar's previous-month button.
  String get previousMonth;

  /// The label of a calendar's next-month button.
  String get nextMonth;

  /// Today, added to the accessible name of today's date in a calendar.
  String get today;

  /// The accessible name of the day a range starts on; [date] is
  /// already formatted.
  String rangeStartDate(String date);

  /// The accessible name of the day a range ends on; [date] is already
  /// formatted.
  String rangeEndDate(String date);

  /// The heading of a date picker.
  String get selectDate;

  /// The heading of a date range picker.
  String get selectDateRange;

  /// The accessible name of the navigation drawer.
  String get navigationMenu;

  /// What activating a collapsed node or panel does: it expands.
  String get expand;

  /// What activating an expanded node or panel does: it collapses.
  String get collapse;

  /// The label of a button that goes on to the next step.
  String get proceed;

  /// The name of the Control key, in a shortcut written out.
  String get keyboardKeyControl;

  /// The name of the Alt key, in a shortcut written out.
  String get keyboardKeyAlt;

  /// The name of the Shift key, in a shortcut written out.
  String get keyboardKeyShift;

  /// The name of the Meta key, elsewhere than on Windows, in a shortcut written out.
  String get keyboardKeyMeta;

  /// The name of the Windows key, in a shortcut written out.
  String get keyboardKeyMetaWindows;

  /// The name of the Backspace key, in a shortcut written out.
  String get keyboardKeyBackspace;

  /// The name of the Delete key, in a shortcut written out.
  String get keyboardKeyDelete;

  /// The name of the End key, in a shortcut written out.
  String get keyboardKeyEnd;

  /// The name of the Escape key, in a shortcut written out.
  String get keyboardKeyEscape;

  /// The name of the Home key, in a shortcut written out.
  String get keyboardKeyHome;

  /// The name of the Insert key, in a shortcut written out.
  String get keyboardKeyInsert;

  /// The name of the Page Down key, in a shortcut written out.
  String get keyboardKeyPageDown;

  /// The name of the Page Up key, in a shortcut written out.
  String get keyboardKeyPageUp;

  /// The name of the space bar, in a shortcut written out.
  String get keyboardKeySpace;

  /// The name of the Caps Lock key, in a shortcut written out.
  String get keyboardKeyCapsLock;

  /// The name of the Print Screen key, in a shortcut written out.
  String get keyboardKeyPrintScreen;

  /// The name of the Scroll Lock key, in a shortcut written out.
  String get keyboardKeyScrollLock;

  /// The name of the Num Lock key, in a shortcut written out.
  String get keyboardKeyNumLock;

  /// The name of the Fn key, in a shortcut written out.
  String get keyboardKeyFn;
}

