/// The kit's own strings, in English, French and Arabic.
///
/// Register [localizationsDelegates] (this [delegate] plus Material's, from
/// material_ui) and read the strings with `context.adminL10n`:
///
/// ```dart
/// MaterialApp(
///   localizationsDelegates: AdminLocalizations.localizationsDelegates,
///   supportedLocales: AdminLocalizations.supportedLocales,
/// )
/// ```
///
/// Without the delegate nothing fails: [of] answers English. A language the
/// kit has no strings for, German say, also gets English strings, while
/// numbers and dates still follow the app's locale ([AdminFormats]). In a
/// right-to-left language without strings, such as Hebrew, that English sits
/// in right-to-left text, where a trailing ellipsis or number lands on the
/// wrong side; an app shipping one should supply its strings (below).
///
/// A widget resolves each of its strings in this order:
///
/// 1. The widget's own label parameter, when the caller passed one.
/// 2. [MaterialLocalizations], for a string it already has (below).
/// 3. The shared vocabulary on this class: words two or more areas of the
///    kit use, such as [apply], [retry] or [selectedCount].
/// 4. The area's section: [inputs], [display], [collection], [fields],
///    [shell] or [assets].
///
/// These come from [MaterialLocalizations] and are not repeated here:
/// `cancelButtonLabel`, `okButtonLabel`, `closeButtonTooltip` and
/// `closeButtonLabel`, `searchFieldLabel`, `clearButtonTooltip`,
/// `modalBarrierDismissLabel`, `copyButtonLabel`, `deleteButtonTooltip`,
/// `saveButtonLabel`, `moreButtonTooltip`, `selectAllButtonLabel`,
/// `backButtonTooltip`, `previousMonthTooltip` and `nextMonthTooltip`,
/// `pageRowsInfoTitle`, `rowsPerPageTitle`, `firstPageTooltip`,
/// `lastPageTooltip`, `nextPageTooltip` and `previousPageTooltip`, and the
/// `keyboardKey*` names (see [shortcutLabel]).
///
/// To change strings, subclass [AdminLocalizationsEn] (or a section's En
/// class, returned from the section getter) and load it from a delegate of
/// your own, listed before [localizationsDelegates]; the first delegate of a
/// type wins:
///
/// ```dart
/// class MyInputs extends InputsMessagesEn {
///   const MyInputs();
///   // @override members of InputsMessages here.
/// }
///
/// class MyAdminL10n extends AdminLocalizationsEn {
///   const MyAdminL10n();
///   @override
///   String get apply => 'Go';
///   @override
///   InputsMessages get inputs => const MyInputs();
/// }
///
/// class MyAdminL10nDelegate
///     extends LocalizationsDelegate<AdminLocalizations> {
///   const MyAdminL10nDelegate();
///   @override
///   bool isSupported(Locale locale) => true;
///   @override
///   Future<AdminLocalizations> load(Locale locale) => SynchronousFuture(
///     locale.languageCode == 'en'
///         ? const MyAdminL10n()
///         : AdminLocalizations.lookup(locale),
///   );
///   @override
///   bool shouldReload(MyAdminL10nDelegate old) => false;
/// }
/// ```
///
/// Hand-written rather than generated by gen-l10n, whose output imports
/// `package:flutter_localizations` (the SDK copy of Material this repo does not
/// use) and whose `of` asserts when the delegate is missing.
abstract class AdminLocalizations extends AdminMessages {
  const AdminLocalizations(super.localeName);

  /// Loads the strings for an app's locale by its language, so fr_CA gets
  /// French. It accepts every locale, answering English for a language the
  /// kit has no strings for, so listing any locale in an app's
  /// `supportedLocales` raises no missing-delegate warning.
  static const LocalizationsDelegate<AdminLocalizations> delegate =
      _AdminLocalizationsDelegate();

  /// The locales the kit has strings for.
  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('fr'),
    Locale('ar'),
  ];

  /// [delegate] and material_ui's Material, Cupertino and widgets delegates:
  /// everything an app passes as `localizationsDelegates` for the kit.
  static const localizationsDelegates = <LocalizationsDelegate<Object?>>[
    delegate,
    ...GlobalMaterialLocalizations.delegates,
  ];

  /// The strings for [context]'s locale, or English when no delegate is
  /// registered above it. Never asserts.
  static AdminLocalizations of(BuildContext context) =>
      Localizations.of<AdminLocalizations>(context, AdminLocalizations) ??
      const AdminLocalizationsEn();

  /// The kit's own strings for [locale]'s language, English when there are
  /// none: what [delegate] loads.
  static AdminLocalizations lookup(Locale locale) =>
      switch (locale.languageCode) {
        'fr' => const AdminLocalizationsFr(),
        'ar' => const AdminLocalizationsAr(),
        _ => const AdminLocalizationsEn(),
      };

  /// The inputs, menus, pickers and overlays in common/ui.
  InputsMessages get inputs;

  /// The layout, data display, feedback, history, menu-editor and
  /// block-picker widgets.
  DisplayMessages get display;

  /// The collection kit: the table, toolbar, filters, pager and views.
  CollectionMessages get collection;

  /// The field bodies, the language lanes and their translation status
  /// words, and the comments capability.
  FieldsMessages get fields;

  /// The app shell, the auth forms and the generic form save flow.
  ShellMessages get shell;

  /// The asset library, picker, cropper and editor.
  AssetsMessages get assets;

  /// A button that applies pending choices, such as a filter's.
  String get apply;

  /// A button that repeats what failed.
  String get retry;

  /// Takes something out of a list or a field, without deleting it.
  String get remove;

  /// [remove] for one named thing: an accessible name, a tooltip.
  String removeItem(String name);

  /// Puts settings back to their defaults.
  String get reset;

  /// Something is on its way, with a trailing ellipsis.
  String get loading;

  /// Changes are being saved, with a trailing ellipsis.
  String get saving;

  /// A value or a record differs from its saved version.
  String get edited;

  /// A form, or a view, has changes that are not saved yet.
  String get unsavedChanges;

  /// A search found nothing.
  String get noResults;

  /// A filter over a loaded list kept nothing.
  String get noMatches;

  /// Data could not be fetched: a list, a preview, a set of options.
  String get couldNotLoad;

  /// A search request failed, as opposed to finding nothing.
  String get searchFailed;

  /// Fetches the next page of a list.
  String get loadMore;

  /// A search request is in flight, with a trailing ellipsis.
  String get searching;

  /// The headline of an error with no better description.
  String get somethingWentWrong;

  /// A whole sentence for an error with no better description.
  String get somethingWentWrongTryAgain;

  /// The overflow menu of secondary actions.
  String get moreActions;

  /// Deselects everything.
  String get clearSelection;

  /// Reorders an item one place earlier.
  String get moveUp;

  /// Reorders an item one place later.
  String get moveDown;

  /// The placeholder of a select with nothing chosen.
  String get selectPlaceholder;

  /// The placeholder of a filter box inside a list.
  String get filterPlaceholder;

  /// The placeholder of a search box.
  String get searchPlaceholder;

  /// Appends an item to a list or a repeater.
  String get addItem;

  /// Appends a row to a table or a key-value list.
  String get addRow;

  /// The key column of a key-value list.
  String get keyLabel;

  /// The value column of a key-value list.
  String get valueLabel;

  /// The placeholder of a reference picker with nothing linked.
  String get linkPlaceholder;

  /// Puts one field back to its published value.
  String get restoreLiveVersion;

  /// A referenced asset that no longer exists.
  String get assetNotFound;

  /// The accessible name of an asset's thumbnail.
  String get assetPreview;

  /// An upload that did not complete.
  String get uploadFailed;

  /// The prompt of an upload drop zone, split around the part drawn as a
  /// link: `before`, `link` and `after` read together as "Drag & drop
  /// files, or browse". [multiple] asks for files rather than a file, and
  /// [images] names images rather than files.
  ({String before, String link, String after}) dropPrompt({
    required bool multiple,
    bool images = false,
  });

  /// How many items are selected, "Nothing selected" at zero.
  String selectedCount(int count);

  /// [count] out of [total]: "3 of 12".
  String countOf(int count, int total);

  /// A byte size: [amount] is already formatted in the unit of 1000^[power]
  /// bytes, 0 for bytes up to 4 for terabytes. Used by
  /// [AdminFormats.bytes].
  String byteSize(String amount, int power);
}

