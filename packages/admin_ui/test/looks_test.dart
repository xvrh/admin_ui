// looks.txt against the tokens the shipped themes resolve to. A change of
// look shows in its diff, and README.md ("Versions") counts one as breaking.
// Rewrite both files with `dart run tool/gen_looks.dart`.

import 'dart:io';

import 'package:admin_ui/admin_ui.dart';
import 'package:flutter_test/flutter_test.dart';

import '../tool/gen_looks.dart' as gen;
import 'looks/describe.gen.dart';

const _path = 'looks.txt';

Map<String, String> _describe(AdminTokens tokens) {
  final out = <String, String>{};
  describeAdminTokens(tokens, '', out);
  return out;
}

/// looks.txt: each theme's light tokens in full, then what its dark tokens
/// change, then what the tokens drawn with no theme above change from Iris's.
String looks() {
  final out = StringBuffer()
    ..writeln("# Every shipped theme's tokens, as the kit resolves them.")
    ..writeln('# Generated by tool/gen_looks.dart; test/looks_test.dart fails')
    ..writeln('# when it is stale. A changed line is a change of look.');

  void section(String title, Map<String, String> lines, [String? empty]) {
    out
      ..writeln()
      ..writeln('## $title');
    if (lines.isEmpty && empty != null) out.writeln(empty);
    for (final MapEntry(:key, :value) in lines.entries) {
      out.writeln('$key: $value');
    }
  }

  Map<String, String> changes(
    Map<String, String> from,
    Map<String, String> to,
  ) => {
    for (final MapEntry(:key, :value) in to.entries)
      if (from[key] != value) key: value,
  };

  for (final theme in adminThemes) {
    final light = _describe(theme.tokens);
    section('${theme.name} light', light);
    final dark = theme.dark;
    section(
      '${theme.name} dark, where it differs from light',
      dark == null ? const {} : changes(light, _describe(dark)),
      dark == null ? '(no dark tokens: dark mode draws the light ones)' : null,
    );
  }
  section(
    'defaultTokens, where they differ from Iris light',
    changes(_describe(irisTheme.tokens), _describe(defaultTokens)),
  );
  return out.toString();
}

void main() {
  test('the generated walk covers every token field', () {
    expect(
      File(gen.describerPath).readAsStringSync(),
      gen.generateDescribers(Directory.current.path),
      reason: 'Run dart run tool/gen_looks.dart',
    );
  });

  test('looks.txt is every theme as it resolves', () {
    final now = looks();
    if (Platform.environment['UPDATE_LOOKS'] == '1') {
      File(_path).writeAsStringSync(now);
      return;
    }
    expect(
      File(_path).readAsStringSync(),
      now,
      reason: 'Run dart run tool/gen_looks.dart, and review the diff',
    );
  });
}
